package String.Methods;

public class IndexOf {
    public static void main(String[] args) {
        String s="Durgaa";
        System.out.println(s.indexOf('r'));//if character is present in your string it will gives the index no that which whre your character is present

        System.out.println(s.indexOf('L'));//if your character is not present in the string i will provide -1

        System.out.println(s.indexOf('a'));//if same character repeats in your character string it will always give first accurence characters index it present first
    }

}
