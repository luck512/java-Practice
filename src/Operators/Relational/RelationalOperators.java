package Operators.Relational;

public class RelationalOperators {
    public static void main(String[] args){
        int p=55, q=22;
        System.out.println(p < q);
        System.out.println(p > q);
        System.out.println(p == q);
        System.out.println(p != q);
        System.out.println(p <= q);
        System.out.println(p >= q);

    }
}
